// Generates src/utils/assetLoaders.ts: one dynamic import() per local logo, so that
// each asset becomes a separate chunk loaded on demand (see LocalIcon.tsx).
import { readdirSync, writeFileSync } from "node:fs";

const ASSETS_DIR = "src/assets/social-icons";
const OUT = "src/utils/assetLoaders.ts";

const files = readdirSync(ASSETS_DIR)
  .filter((f) => /\.(png|svg|jpg|webp)$/.test(f))
  .sort();

const lines = files.map(
  (f) => `  ${JSON.stringify(f)}: () => import("../assets/social-icons/${f}"),`,
);

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-asset-loaders.mjs, do not edit
export const assetLoaders = {
${lines.join("\n")}
} as const;

export type AssetName = keyof typeof assetLoaders;
`,
);

console.error(`${OUT}: ${files.length} assets`);
